export const normalizeDishName = (name: string) =>
  name
    .trim()
    .toLocaleLowerCase('tr')
    .replace(/ı/g, 'i')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/\s+/g, ' ');
export const findDishTemplate = (name: string) =>
  DISH_CATALOG.find((dish) =>
    [dish.name, ...dish.aliases].some(
      (alias) => normalizeDishName(alias) === normalizeDishName(name),
    ),
  );
